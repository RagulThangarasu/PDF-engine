def test_repeated_header_on_every_continuation_page_passes():
    result = _tables("tables_prod.pdf", "tables_stage_ok.pdf")
    assert "Table header row not repeated on continuation page" not in result.message_counts
    row = result.summary_rows[0]
    assert row["header_repeated"] == "Yes"
    assert row["actual_span"] == "3 pages"


def test_missing_header_on_continuation_pages_is_an_error():
    """The rule the report exists to enforce: a Staging table that runs onto
    another page must reprint its header there."""
    result = _tables("tables_prod.pdf", "tables_stage_noheader.pdf")
    count = result.message_counts.get("Table header row not repeated on continuation page")
    assert count == 2, result.message_counts  # the table spans three pages

    issues = [i for i in result.issues if i.message.startswith("Table header row not repeated")]
    assert [i.page for i in issues] == [1, 2], "should name the continuation pages, not the first page"
    for issue in issues:
        assert issue.severity == "error"
        assert issue.details["header_row"].startswith("Item")
        # The row actually printed there is quoted, so the reader can see what
        # took the header's place.
        assert issue.details["first_row_on_continuation"].startswith("Setting")
    assert result.summary_rows[0]["header_repeated"] == "NO"
    assert result.summary_rows[0]["status"] == "Issues"


def test_missing_header_is_reported_even_without_a_production_counterpart():
    """The rule holds against Staging alone - it must not depend on the table
    pairing with anything in Production."""
    result = _tables("images_prod.pdf", "tables_stage_noheader.pdf")
    assert result.message_counts.get("Table header row not repeated on continuation page") == 2


def test_identical_documents_report_no_table_findings():
    result = _tables("tables_prod.pdf", "tables_prod.pdf")
    assert result.message_counts == {}, result.message_counts


def test_table_running_past_the_right_margin_is_captured():
    """A Staging table whose right edge sits well past the page's established
    content margin must be flagged."""
    result = _tables("tables_prod.pdf", "tables_stage_overflow.pdf")
    n = result.message_counts.get("Table breaking the margins")
    assert n and n >= 1, result.message_counts
    issue = next(i for i in result.issues if i.message == "Table breaking the margins")
    assert "right margin by" in issue.details["overflow"]
    # and it must NOT fire when the table sits inside the margin
    ok = _tables("tables_prod.pdf", "tables_stage_ok.pdf")
    assert "Table breaking the margins" not in ok.message_counts


def _run_all() -> int:
    failures = 0
    for name, fn in sorted(globals().items()):
        if not name.startswith("test_") or not callable(fn):
            continue
        try:
            fn()
            print(f"PASS {name}")
        except AssertionError as exc:
            failures += 1
            print(f"FAIL {name}: {exc}")
    print(f"\n{failures} failure(s)")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(_run_all())
